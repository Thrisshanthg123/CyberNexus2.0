import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Check, CheckCheck, ExternalLink, ShieldAlert } from 'lucide-react';
import { Panel, Badge, Button, Tooltip } from '../../components/ui';
import { useAsync } from '../../hooks';
import { api } from '../../services/api';
import { Alert } from '../../types';

export const AlertsPage: React.FC = () => {
  const navigate = useNavigate();
  const alertsAsync = useAsync(() => api.getAlerts());
  const [alerts, setAlerts] = useState<Alert[]>([]);

  React.useEffect(() => {
    if (alertsAsync.data) {
      setAlerts(alertsAsync.data);
    }
  }, [alertsAsync.data]);

  const markAllAsRead = () => {
    setAlerts(prev => prev.map(a => ({ ...a, read: true })));
  };

  const toggleRead = (id: string) => {
    setAlerts(prev => prev.map(a => (a.id === id ? { ...a, read: !a.read } : a)));
  };

  const unreadCount = alerts.filter(a => !a.read).length;

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 'var(--space-5)', maxWidth: '1440px', margin: '0 auto' }}>
      {/* Header */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: 'var(--space-3)' }}>
        <div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-2)' }}>
            <h1 style={{ fontSize: 'var(--text-xl)', fontWeight: 700 }}>Security Operations Center Alerts</h1>
            <Badge variant="simulated">Simulated data</Badge>
          </div>
          <p style={{ color: 'var(--color-text-small)', fontSize: 'var(--text-sm)', marginTop: '4px' }}>
            Real-time critical notices generated by automated cross-source correlation rules.
          </p>
        </div>

        <div>
          <Tooltip
            content={
              unreadCount === 0
                ? 'All alerts already marked as read'
                : `Mark ${unreadCount} unread security notifications as read.`
            }
          >
            <div>
              <Button
                variant="outline"
                onClick={markAllAsRead}
                disabled={unreadCount === 0}
                aria-disabled={unreadCount === 0 ? 'true' : undefined}
                icon={<CheckCheck size={14} />}
              >
                Mark All as Read ({unreadCount})
              </Button>
            </div>
          </Tooltip>
        </div>
      </div>

      {/* Alerts List */}
      <Panel title={`Active Operational Alerts (${alerts.length})`}>
        <div style={{ display: 'flex', flexDirection: 'column', gap: 'var(--space-3)' }}>
          {alerts.map(alert => (
            <div
              key={alert.id}
              style={{
                display: 'flex',
                alignItems: 'flex-start',
                justifyContent: 'space-between',
                padding: 'var(--space-4)',
                background: alert.read ? 'var(--color-raised)' : 'var(--accent-blue-tint)',
                border: '1px solid',
                borderColor: alert.read ? 'var(--color-border)' : 'var(--accent-blue-border)',
                borderRadius: 'var(--radius-chip)',
                gap: 'var(--space-4)'
              }}
            >
              <div style={{ display: 'flex', gap: 'var(--space-3)' }}>
                <ShieldAlert
                  size={20}
                  color={alert.severity === 'critical' ? 'var(--severity-critical)' : 'var(--severity-high)'}
                  style={{ flexShrink: 0, marginTop: '2px' }}
                />
                <div>
                  <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-2)', marginBottom: '4px' }}>
                    <span style={{ fontWeight: 600, color: 'var(--color-text)', fontSize: 'var(--text-sm)' }}>
                      {alert.title}
                    </span>
                    <Badge variant={alert.severity}>{alert.severity}</Badge>
                    {!alert.read && <Badge variant="critical">UNREAD</Badge>}
                  </div>
                  <p style={{ fontSize: 'var(--text-xs)', color: 'var(--color-text-small)', lineHeight: 1.5, marginBottom: '6px' }}>
                    {alert.message}
                  </p>
                  <div style={{ fontSize: '11px', color: 'var(--color-text-muted)', fontFamily: 'var(--font-mono)' }}>
                    Source: {alert.source} • Ingested: {new Date(alert.timestamp).toLocaleString()}
                  </div>
                </div>
              </div>

              <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-2)', flexShrink: 0 }}>
                {alert.threatId && (
                  <Button
                    variant="outline"
                    onClick={() => navigate(`/dashboard/threats/${alert.threatId}`)}
                    style={{ minHeight: '28px', padding: '2px 8px', fontSize: 'var(--text-xs)' }}
                    icon={<ExternalLink size={12} />}
                  >
                    Threat Dossier
                  </Button>
                )}
                <Button
                  variant="outline"
                  onClick={() => toggleRead(alert.id)}
                  style={{ minHeight: '28px', padding: '2px 8px', fontSize: 'var(--text-xs)' }}
                  icon={<Check size={12} />}
                >
                  {alert.read ? 'Mark Unread' : 'Acknowledge'}
                </Button>
              </div>
            </div>
          ))}
        </div>
      </Panel>
    </div>
  );
};
